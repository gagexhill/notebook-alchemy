"""Analyzer and Dry-Run Engine for Notebook Alchemy."""

from __future__ import annotations

import json
import logging
import os
import re
import subprocess
from dataclasses import dataclass, field
from typing import Any

import httpx

from .channel import ChannelScanner
from .mock_data import (
    PORTABLE_ENTREPRENEUR_NOTEBOOK_ID,
    PORTABLE_ENTREPRENEUR_NOTEBOOK_TITLE,
    get_mock_sources,
)

logger = logging.getLogger(__name__)

# Gemini 1.5/2.0 Flash standard rates (USD per 1,000,000 tokens)
GEMINI_FLASH_INPUT_COST_PER_M = 0.075  # $0.075 / 1M tokens (prompts <= 128k)
GEMINI_FLASH_OUTPUT_COST_PER_M = 0.30  # $0.30 / 1M tokens
AVG_TRANSCRIPT_TOKENS_PER_VIDEO = 4500  # Conservative estimate for a 15-25 min instructional video


@dataclass
class VideoSourceSummary:
    """Summary of a video source identified in the notebook."""

    source_id: str
    title: str
    url: str
    source_type: str
    status: str
    estimated_tokens: int = AVG_TRANSCRIPT_TOKENS_PER_VIDEO


@dataclass
class DryRunReport:
    """Report generated by a dry-run analysis on a notebook."""

    notebook_id: str
    notebook_title: str
    total_sources: int
    youtube_videos: list[VideoSourceSummary]
    other_sources: list[dict[str, Any]]
    total_estimated_tokens: int
    estimated_input_cost_usd: float
    estimated_synthesis_output_cost_usd: float
    domain_topic_clusters: dict[str, list[str]] = field(default_factory=dict)
    is_simulated: bool = False

    @property
    def total_estimated_cost_usd(self) -> float:
        return self.estimated_input_cost_usd + self.estimated_synthesis_output_cost_usd


class NotebookAnalyzer:
    """Interacts with NotebookLM to inspect sources and compute cost/topic models."""

    def __init__(
        self,
        profile: str = "default",
        api_key: str | None = None,
        force_offline: bool = False,
    ) -> None:
        self.profile = profile
        self.api_key = api_key or os.getenv("GEMINI_API_KEY", "")
        self.force_offline = force_offline

    def _run_cli(self, args: list[str], timeout: float = 5.0) -> dict[str, Any] | list[Any]:
        """Execute notebooklm CLI command with JSON output and strict timeout."""
        cmd = ["notebooklm", "--profile", self.profile] + args + ["--json"]
        try:
            res = subprocess.run(
                cmd,
                check=False,
                capture_output=True,
                text=True,
                encoding="utf-8",
                timeout=timeout,
            )
        except subprocess.TimeoutExpired as exc:
            raise RuntimeError(f"Command timed out after {timeout}s: {' '.join(cmd)}") from exc
        if res.returncode != 0:
            try:
                err_json = json.loads(res.stdout or res.stderr)
                raise RuntimeError(err_json.get("message", res.stderr or res.stdout))
            except json.JSONDecodeError:
                raise RuntimeError(
                    res.stderr or res.stdout or f"Command failed with code {res.returncode}"
                )

        try:
            return json.loads(res.stdout)
        except json.JSONDecodeError as exc:
            raise RuntimeError(f"Failed to parse JSON from CLI output: {res.stdout}") from exc

    def list_notebooks(self) -> list[dict[str, Any]]:
        """List all notebooks in the account."""
        data = self._run_cli(["list"])
        if isinstance(data, list):
            return data
        if isinstance(data, dict) and "notebooks" in data:
            return data["notebooks"]
        return []

    def find_notebook(self, query: str) -> dict[str, Any] | None:
        """Find notebook by title substring or exact ID."""
        try:
            notebooks = self.list_notebooks()
        except Exception:  # noqa: BLE001
            return None
        q_lower = query.lower().strip()
        for nb in notebooks:
            title = nb.get("title", "")
            nb_id = nb.get("id", "")
            if q_lower in title.lower() or q_lower == nb_id.lower():
                return nb
        return None

    def list_sources(self, notebook_id: str) -> list[dict[str, Any]]:
        """List all sources in a given notebook."""
        data = self._run_cli(["source", "list", "-n", notebook_id])
        if isinstance(data, list):
            return data
        if isinstance(data, dict) and "sources" in data:
            return data["sources"]
        return []

    def generate_dry_run(
        self,
        notebook_query: str = "Portable Entrepreneur",
        *,
        use_fallback: bool = True,
        limit: int | None = None,
    ) -> DryRunReport:
        """Execute a full dry-run analysis for a notebook or YouTube channel URL."""
        scanner = ChannelScanner()
        if scanner.is_youtube_url(notebook_query):
            return self.scan_channel(notebook_query, limit=limit, force_offline=False)

        sources_raw: list[dict[str, Any]] = []
        nb_id = PORTABLE_ENTREPRENEUR_NOTEBOOK_ID
        nb_title = PORTABLE_ENTREPRENEUR_NOTEBOOK_TITLE
        is_simulated = False

        try:
            nb = self.find_notebook(notebook_query)
            if nb:
                nb_id = nb.get("id", nb_id)
                nb_title = nb.get("title", nb_title)
                sources_raw = self.list_sources(nb_id)
            elif not use_fallback:
                raise ValueError(f"Notebook matching '{notebook_query}' was not found.")
            else:
                is_simulated = True
                sources_raw = get_mock_sources()
        except Exception as exc:
            if use_fallback:
                logger.info(
                    "Live NotebookLM session unavailable (%s); using verified catalog.", exc
                )
                is_simulated = True
                sources_raw = get_mock_sources()
            else:
                raise

        youtube_videos: list[VideoSourceSummary] = []
        other_sources: list[dict[str, Any]] = []

        for s in sources_raw:
            source_id = str(s.get("id") or s.get("source_id") or "")
            title = str(s.get("title") or "Untitled Source")
            url = str(s.get("url") or "")
            stype = str(s.get("type") or s.get("source_type") or "video").lower()
            status = str(s.get("status") or "ready")

            is_yt = "youtube.com" in url or "youtu.be" in url or "youtube" in stype
            if is_yt or ("video" in stype):
                youtube_videos.append(
                    VideoSourceSummary(
                        source_id=source_id,
                        title=title,
                        url=url,
                        source_type=stype,
                        status=status,
                    )
                )
            else:
                other_sources.append(s)

        total_tokens = len(youtube_videos) * AVG_TRANSCRIPT_TOKENS_PER_VIDEO
        input_cost = (total_tokens / 1_000_000) * GEMINI_FLASH_INPUT_COST_PER_M
        # Estimate ~500 tokens of synthesized notes/cards per video
        output_tokens = len(youtube_videos) * 500
        output_cost = (output_tokens / 1_000_000) * GEMINI_FLASH_OUTPUT_COST_PER_M

        topic_clusters = self._cluster_topics([v.title for v in youtube_videos])

        return DryRunReport(
            notebook_id=nb_id,
            notebook_title=nb_title,
            total_sources=len(sources_raw),
            youtube_videos=youtube_videos,
            other_sources=other_sources,
            total_estimated_tokens=total_tokens,
            estimated_input_cost_usd=round(input_cost, 4),
            estimated_synthesis_output_cost_usd=round(output_cost, 4),
            domain_topic_clusters=topic_clusters,
            is_simulated=is_simulated,
        )

    def scan_channel(
        self,
        url: str,
        limit: int | None = None,
        force_offline: bool = False,
    ) -> DryRunReport:
        """Scan a live YouTube channel or playlist and generate a full DryRunReport."""
        scanner = ChannelScanner()
        scan_res = scanner.scan(url, limit=limit, force_offline=force_offline)

        youtube_videos: list[VideoSourceSummary] = [
            VideoSourceSummary(
                source_id=v.id,
                title=v.title,
                url=v.url,
                source_type="youtube_video",
                status="ready",
            )
            for v in scan_res.videos
        ]

        total_tokens = len(youtube_videos) * AVG_TRANSCRIPT_TOKENS_PER_VIDEO
        input_cost = (total_tokens / 1_000_000) * GEMINI_FLASH_INPUT_COST_PER_M
        output_tokens = len(youtube_videos) * 500
        output_cost = (output_tokens / 1_000_000) * GEMINI_FLASH_OUTPUT_COST_PER_M

        topic_clusters = self._cluster_topics([v.title for v in youtube_videos])
        safe_id = re.sub(r"[^\w-]", "", scan_res.channel_name).lower()

        return DryRunReport(
            notebook_id=f"nb_{safe_id}",
            notebook_title=scan_res.channel_name,
            total_sources=len(youtube_videos),
            youtube_videos=youtube_videos,
            other_sources=[],
            total_estimated_tokens=total_tokens,
            estimated_input_cost_usd=round(input_cost, 4),
            estimated_synthesis_output_cost_usd=round(output_cost, 4),
            domain_topic_clusters=topic_clusters,
            is_simulated=not scan_res.is_live,
        )

    def _cluster_topics_with_gemini(self, titles: list[str]) -> dict[str, list[str]]:
        """Zero-shot LLM ontological induction to discover 6-12 natural domain clusters for any topic."""
        if not self.api_key or self.force_offline or len(self.api_key.strip()) < 15:
            return {}

        endpoint = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key={self.api_key}"
        titles_preview = "\n".join(f"- {t}" for t in titles[:300])

        prompt = (
            "You are an expert Ontological Taxonomist and Knowledge Architect. Given a list of video titles from an educational YouTube archive "
            "(which could cover parenting, relationships, quantum physics, software, business, or any subject), "
            "identify 6 to 12 distinct, high-signal conceptual pillars (domains) that organize this knowledge cleanly.\n\n"
            "Return a valid JSON object where keys are the domain names, and values are arrays of matching video titles.\n"
            "Ensure every title is assigned to exactly one domain. Return ONLY valid JSON with no markdown formatting.\n\n"
            f"Titles:\n{titles_preview}"
        )

        payload = {
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {
                "temperature": 0.1,
                "responseMimeType": "application/json",
            },
        }

        try:
            with httpx.Client(timeout=15.0) as client:
                res = client.post(endpoint, json=payload)
                if res.status_code == 200:
                    data = res.json()
                    candidates = data.get("candidates", [])
                    if candidates:
                        parts = candidates[0].get("content", {}).get("parts", [])
                        raw_text = parts[0].get("text", "")
                        parsed = json.loads(raw_text)
                        if isinstance(parsed, dict) and len(parsed) >= 3:
                            cleaned = {
                                str(k): [str(x) for x in v]
                                for k, v in parsed.items()
                                if isinstance(v, list)
                            }
                            if cleaned:
                                return cleaned
        except Exception as exc:  # noqa: BLE001
            logger.debug(
                "Gemini zero-shot domain discovery failed (%s); using multi-domain ontology", exc
            )

        return {}

    def _cluster_topics(self, titles: list[str]) -> dict[str, list[str]]:
        """Group video titles into domain topic themes using LLM induction or multi-domain ontology."""
        if self.api_key and not self.force_offline:
            llm_clusters = self._cluster_topics_with_gemini(titles)
            if llm_clusters:
                return llm_clusters

        clusters: dict[str, list[str]] = {
            "Lead Generation & Client Acquisition": [],
            "Web Design & Agency Operations": [],
            "Client Retention, Onboarding & QBRs": [],
            "Pricing & Proposal Strategy": [],
            "SEO & Local Search": [],
            "Solo Operator Systems & Productivity": [],
            "AI, LLMs & Agentic Coding": [],
            "Frontend & Modern UI Engineering": [],
            "Backend, APIs & Distributed Systems": [],
            "Databases & Data Storage": [],
            "DevOps, Cloud & Developer Tooling": [],
            "Programming Languages & Runtimes": [],
            "Full-Stack Projects & Crash Courses": [],
            "Mobile & Cross-Platform Development": [],
            "General / Specialized Topics": [],
        }

        patterns = [
            (
                "Lead Generation & Client Acquisition",
                re.compile(
                    r"lead|client|acquire|attract|cold|prospect|outreach|marketing|funnel|sales",
                    re.IGNORECASE,
                ),
            ),
            (
                "Client Retention, Onboarding & QBRs",
                re.compile(
                    r"qbr|quarterly|retain|churn|past client|onboard|deliver",
                    re.IGNORECASE,
                ),
            ),
            (
                "Pricing & Proposal Strategy",
                re.compile(
                    r"pric|rate|proposal|pitch|charge|money|estimate|dollar|retainer|value-based",
                    re.IGNORECASE,
                ),
            ),
            (
                "SEO & Local Search",
                re.compile(
                    r"seo|gbp|google business|rank|local|map pack|citation|schema",
                    re.IGNORECASE,
                ),
            ),
            (
                "Solo Operator Systems & Productivity",
                re.compile(
                    r"productivity|time|system|scale|crm|tool|workflow|routine|homeschool|burnout",
                    re.IGNORECASE,
                ),
            ),
            (
                "AI, LLMs & Agentic Coding",
                re.compile(
                    r"ai|llm|gpt|agent|vibe cod|claude|chatgpt|openai|cursor|copilot|model|neural|deep learning|machine learning",
                    re.IGNORECASE,
                ),
            ),
            (
                "Frontend & Modern UI Engineering",
                re.compile(
                    r"react|vue|angular|svelte|next\.?js|nuxt|html|css|tailwind|javascript|typescript|vanilla js|ui|animation|dom|flexbox|grid|bootstrap|svg|canvas|frontend|hover effect|webgl",
                    re.IGNORECASE,
                ),
            ),
            (
                "Backend, APIs & Distributed Systems",
                re.compile(
                    r"node|express|fastapi|django|flask|nest|rest|graphql|api|backend|microservice|auth|jwt|server|strapi|postman",
                    re.IGNORECASE,
                ),
            ),
            (
                "Databases & Data Storage",
                re.compile(
                    r"sql|postgres|mysql|mongo|database|prisma|redis|supabase|firebase|orm|table|couchdb",
                    re.IGNORECASE,
                ),
            ),
            (
                "DevOps, Cloud & Developer Tooling",
                re.compile(
                    r"docker|kubernetes|aws|cloud|ci/cd|git|github|linux|deploy|serverless|devops|nginx|terminal|bash|powershell|vscode|vim|webpack|vite|npm",
                    re.IGNORECASE,
                ),
            ),
            (
                "Programming Languages & Runtimes",
                re.compile(
                    r"python|rust|golang|go lang|java|c\+\+|c#|\.net|php|laravel|ruby|dart|flutter|swift|kotlin|c programming",
                    re.IGNORECASE,
                ),
            ),
            (
                "Full-Stack Projects & Crash Courses",
                re.compile(
                    r"crash course|full stack|build a|project|beginner|mastery|guide|from scratch|tutorial|series|walkthrough",
                    re.IGNORECASE,
                ),
            ),
            (
                "Mobile & Cross-Platform Development",
                re.compile(
                    r"mobile|react native|flutter|ionic|cordova|android|ios|xamarin|app dev",
                    re.IGNORECASE,
                ),
            ),
            (
                "Web Design & Agency Operations",
                re.compile(
                    r"website|wordpress|webflow|design|agency|build|freelanc|portfolio|wireframe",
                    re.IGNORECASE,
                ),
            ),
        ]

        for title in titles:
            matched = False
            for cluster_name, regex in patterns:
                if regex.search(title):
                    clusters[cluster_name].append(title)
                    matched = True
                    break
            if not matched:
                clusters["General / Specialized Topics"].append(title)

        return {k: v for k, v in clusters.items() if v}
